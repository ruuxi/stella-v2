#!/usr/bin/env node
/**
 * Bundle the just-bash worker shell into the modules table the BuildSession
 * hands to the Worker Loader.
 *
 * The shell never runs in the cloud-builder isolate: `src/worker-shell/entry.ts`
 * is the main module of a Dynamic Worker, so the Loader needs it as source
 * text. esbuild splits it so the lazily imported command chunks stay separate
 * modules; workerd parses a chunk only when a command first imports it, so a
 * `cat` never pays for `awk`. Commands the shell never registers (python3,
 * sqlite3, js-exec, curl, html-to-markdown) are replaced by throwing stubs so
 * their runtimes and undici never reach the upload.
 *
 * The output file is gitignored and regenerated by the worker build and by
 * every test script that needs it; `shell-modules.generated.d.ts` is the
 * checked-in type.
 */

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workerRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const outputFile = path.join(
  workerRoot,
  "src/worker-shell/shell-modules.generated.js",
);

/**
 * just-bash chunks that belong only to commands the shell never registers.
 * Matching is by the chunk's file name inside just-bash's own prebuilt
 * bundle, which is stable per pinned version; `check` below fails the build
 * if the pin moves and a stub stops matching.
 */
const EXCLUDED_CHUNKS = [
  "python3",
  "sqlite3",
  "js-exec",
  "curl",
  "html-to-markdown",
];
const EXCLUDED_CHUNK_PATTERN = new RegExp(
  `[/\\\\]chunks[/\\\\](${EXCLUDED_CHUNKS.join("|")})-[A-Z0-9]+\\.js$`,
);

const STUB_NAMESPACE = "stella-worker-shell-stub";

/**
 * Three call sites in just-bash that no parse-time analysis reaches, each
 * patched to report to the current run (`src/worker-shell/entry.ts` defines
 * the global). The patterns are matched against the pinned, minified build
 * and must each apply exactly once; a new just-bash that moves them fails
 * the build here rather than silently losing the check.
 *
 * - A command resolved to a workspace file would run that file as a bash
 *   script, whatever its real interpreter. The hook refuses first.
 * - A name no registered command answers is a program the sandbox may have.
 * - An execution limit ends the script early, after some statements ran.
 * - A command reports, on its own stderr and before any redirection can hide
 *   it, that it does not implement a flag or feature the real tool has.
 */
const HOOK = "globalThis.__stellaWorkerShell";
const PATCHES = [
  {
    name: "user script",
    pattern: /if\("script"in (\w+)\)return /g,
    replace: (_match, resolved) =>
      `if("script"in ${resolved}){${HOOK}?.userScript(${resolved}.path)}if("script"in ${resolved})return `,
  },
  {
    name: "command not found",
    pattern: /(\w+)\(`bash: \$\{(\w+)\}: command not found\n`,127\)/g,
    replace: (match, _failure, name) =>
      `(${HOOK}?.commandNotFound(${name}),${match})`,
  },
  {
    name: "command result",
    pattern:
      /(\w+)=(\w+)\.trusted\?await (\w+)\.runTrustedAsync\((\w+)\):await \4\(\);return\{\.\.\.\1,internalStdinConsumed:/g,
    replace: (match, result, command, runner, run) =>
      match.replace(
        `;return{...${result},`,
        `;${HOOK}?.commandResult(${result});return{...${result},`,
      ),
  },
  {
    name: "execution limit",
    pattern:
      /name="ExecutionLimitError";static EXIT_CODE=126;constructor\((\w+),(\w+)((?:,\w+="")*)\)\{super\(([^)]*)\),/g,
    replace: (match, message) => `${match}${HOOK}?.limit(${message}),`,
  },
];

export const buildWorkerShellModules = async () => {
  const stubbed = new Set();
  const patched = new Map(PATCHES.map((patch) => [patch.name, 0]));
  const result = await build({
    absWorkingDir: workerRoot,
    entryPoints: { shell: "src/worker-shell/entry.ts" },
    bundle: true,
    write: false,
    splitting: true,
    outdir: path.join(workerRoot, ".wrangler/worker-shell-scratch"),
    format: "esm",
    target: "es2022",
    platform: "neutral",
    mainFields: ["module", "main"],
    conditions: ["workerd", "worker", "import"],
    entryNames: "[name]",
    chunkNames: "chunk-[hash]",
    minify: true,
    legalComments: "none",
    external: ["cloudflare:workers", "node:*"],
    plugins: [
      {
        name: "stella-worker-shell-exclusions",
        setup(pluginBuild) {
          pluginBuild.onResolve({ filter: /^\.\/chunks\// }, (args) => {
            const resolved = path.resolve(args.resolveDir, args.path);
            const match = EXCLUDED_CHUNK_PATTERN.exec(resolved);
            if (!match) return undefined;
            stubbed.add(match[1]);
            return { path: match[1], namespace: STUB_NAMESPACE };
          });
          // seek-bzip ships a native binding and is imported statically by
          // tar; bzip2 is not offered, so the import resolves to a stub.
          pluginBuild.onResolve({ filter: /^seek-bzip$/ }, () => {
            stubbed.add("seek-bzip");
            return { path: "seek-bzip", namespace: STUB_NAMESPACE };
          });
          // xz and zstd are reached through guarded dynamic imports.
          pluginBuild.onResolve(
            { filter: /^(node-liblzma|@mongodb-js\/zstd)$/ },
            (args) => ({ path: args.path, namespace: STUB_NAMESPACE }),
          );
          pluginBuild.onLoad(
            { filter: /[/\\]just-bash[/\\]dist[/\\]bundle[/\\].*\.js$/ },
            async (args) => {
              let contents = await readFile(args.path, "utf8");
              for (const patch of PATCHES) {
                contents = contents.replace(patch.pattern, (...match) => {
                  patched.set(patch.name, patched.get(patch.name) + 1);
                  return patch.replace(...match);
                });
              }
              return { contents, loader: "js" };
            },
          );
          pluginBuild.onLoad({ filter: /.*/, namespace: STUB_NAMESPACE }, (args) => ({
            contents: `const unavailable = () => { throw new Error(${JSON.stringify(
              `${args.path} is not available in the Stella worker shell.`,
            )}); };\nexport default new Proxy({}, { get: () => unavailable });\nexport const decode = unavailable;\n`,
            loader: "js",
          }));
        },
      },
    ],
    loader: { ".node": "empty" },
    // just-bash's node build starts with `createRequire(import.meta.url)`.
    // A string-loaded Dynamic Worker module has no URL, and the shell never
    // reaches a real `require`, so any absolute file URL satisfies it.
    define: {
      "import.meta.url": JSON.stringify("file:///shell.js"),
      "process.env.NODE_ENV": '"production"',
    },
    metafile: true,
    logLevel: "warning",
  });
  for (const [name, count] of patched) {
    if (count !== 1) {
      throw new Error(
        `worker shell bundle: the ${name} patch applied ${count} times; the pinned just-bash layout changed.`,
      );
    }
  }
  for (const name of [...EXCLUDED_CHUNKS, "seek-bzip"]) {
    if (!stubbed.has(name)) {
      throw new Error(
        `worker shell bundle: expected to stub ${name}; the pinned just-bash layout changed.`,
      );
    }
  }
  const modules = {};
  let totalBytes = 0;
  for (const file of result.outputFiles) {
    if (!file.path.endsWith(".js")) continue;
    modules[path.basename(file.path)] = { js: file.text };
    totalBytes += file.contents.byteLength;
  }
  if (!modules["shell.js"]) {
    throw new Error("worker shell bundle: esbuild did not emit shell.js.");
  }
  const serialized = JSON.stringify(modules);
  // The Worker Loader caches an isolate per name; naming it by content means
  // a deploy with a new shell never reuses an isolate built from the old one.
  const id = createHash("sha256").update(serialized).digest("hex").slice(0, 16);
  const source = `// Generated by scripts/build-worker-shell.mjs. Do not edit.\nexport default Object.freeze({ id: ${JSON.stringify(id)}, modules: Object.freeze(${serialized}) });\n`;
  await mkdir(path.dirname(outputFile), { recursive: true });
  const staging = `${outputFile}.${process.pid}.tmp`;
  await writeFile(staging, source);
  await rename(staging, outputFile);
  return {
    id,
    modules: Object.keys(modules).length,
    shellBytes: modules["shell.js"].js.length,
    totalBytes,
  };
};

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const summary = await buildWorkerShellModules();
  process.stdout.write(
    `${JSON.stringify({ event: "worker_shell_bundle", ...summary })}\n`,
  );
}
