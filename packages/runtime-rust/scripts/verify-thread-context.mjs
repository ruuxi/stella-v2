// Real process/SQLite integration: working context, immutable transcript and recovery.
import {spawn} from 'node:child_process';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import assert from 'node:assert/strict';
import {attachJsonRpcPeerToStreams} from '../../contracts/protocol/jsonl.ts';
const directory=await mkdtemp(join(tmpdir(),'stella-thread-context-'));
const binary=new URL('../target/debug/stella-runtime',import.meta.url).pathname;
async function launch(){
 const child=spawn(binary,['--database',join(directory,'stella.sqlite')],{stdio:['pipe','pipe','inherit']});
 const {peer}=attachJsonRpcPeerToStreams({input:child.stdout,output:child.stdin,requestTimeoutMs:15000});
 const call=(method,params={})=>peer.request('internal.worker.threads.'+method,params);
 return {call,close:async()=>{child.stdin.end();await new Promise(r=>child.once('exit',r));assert.equal(child.exitCode,0);}};
}
let runtime=await launch();
const threadKey='real-process-checkpoint';const call=(method,args={})=>runtime.call(method,{threadKey,...args});
const timestamp=Date.now();
const append=async(entryType,data,offset)=> (await call('append',{entryType,data,timestamp:timestamp+offset})).entryId;
const message=async(role,content,offset,extra={})=>append('message',{message:{role,content,timestamp:timestamp+offset,...extra}},offset);
let finalMessages,session,raw;
try{
 await call('resolve',{conversationId:'native-context-proof',agentType:'general',threadId:threadKey,nameHint:'Context proof'});
 const resident=await append('custom_message',{customType:'bootstrap.skills_catalog',content:'old skills',display:false},0);
 await append('custom_message',{customType:'runtime.context_delta.tools',content:'old tools delta',display:false},1);
 const first=await message('user','old question',2);
 const huge='x'.repeat(70000);
 const second=await message('assistant',[{type:'text',text:huge}],3,{model:'real-fixture-model',usage:{input:5,output:8,totalTokens:13}});
 const image=await message('user',[{type:'image',mimeType:'image/png',data:'a'.repeat(80000),width:1024,height:1024}],4);
 const last=await message('user','keep latest instruction',5);
 let pressure=await call('pressure');assert.equal(pressure.imageCount,1);assert.equal(pressure.imageDecodedBytes,60000);
 assert(pressure.estimatedTokens<26000,'base64 must not inflate text token estimate');
 raw=await call('entries');assert.equal(raw.find(e=>e.id===second).data.message.content[0].text,huge);
 assert.equal(raw.find(e=>e.id===image).data.message.content[0].data.length,80000);
 session=await call('session');assert.equal(session.sessionId,(await call('session')).sessionId);
 const details={replaceDerivedContext:true,residentFold:{docs:[{customType:'bootstrap.skills_catalog',text:'fresh skills'}]},pinnedUserInstruction:{text:'pinned contract'},imageReceipts:[{id:'sha256:'+'a'.repeat(64),mimeType:'image/png',decodedBytes:60000,origin:{timestamp,role:'user'},artifact:{durability:'durable'}}]};
 await call('compact',{summary:'first checkpoint',fromEntryId:first,toEntryId:image,tokensBefore:pressure.estimatedTokens,timestamp:timestamp+10,details});
 finalMessages=await call('messages');let visible=JSON.stringify(finalMessages);
 assert(!visible.includes('old skills'));assert(!visible.includes('old tools delta'));assert(!visible.includes('old question'));assert(!visible.includes(huge));
 assert(visible.includes('fresh skills'));assert(visible.includes('pinned contract'));assert(visible.includes('first checkpoint'));assert(visible.includes('image-receipts'));assert(visible.includes('keep latest instruction'));
 assert.deepEqual((await call('entries')).slice(0,raw.length),raw,'compaction must not alter exact durable rows');
 assert.equal((await call('pressure')).imageCount,0);
 assert(JSON.stringify(await call('messages',{limit:100})).includes('old question'),'bounded history is a raw view');
 const after=await message('assistant',[{type:'text',text:'new response'}],11);
 await call('compact',{summary:'second checkpoint',fromEntryId:last,toEntryId:after,tokensBefore:200,timestamp:timestamp+12,details});
 const context=await call('context');assert.equal(context.coveredFromSeq,raw.find(e=>e.id===first).seq);
 await assert.rejects(call('compact',{summary:'invalid shrink',fromEntryId:first,toEntryId:second}));
 await assert.rejects(call('compact',{summary:'invalid synthetic boundary',fromEntryId:context.compactionEntryId+'::resident:0',toEntryId:after}));
 const poisoned=await message('toolResult',[{type:'text',text:'durable poisonous payload'}],13,{toolCallId:'call-proof',toolName:'Read',details:{exact:'sensitive blob'}});
 await append('custom_message',{customType:'containment.quarantine',content:JSON.stringify({key:`${timestamp+13}:call-proof`,toolName:'Read',timestamp:timestamp+14}),display:false},14);
 finalMessages=await call('messages');const masked=finalMessages.find(m=>m.toolCallId==='call-proof');assert(masked.content[0].text.startsWith('[content quarantined:'));assert.equal(masked.details,undefined);
 assert.equal((await call('entries')).find(e=>e.id===poisoned).data.message.content[0].text,'durable poisonous payload');
 assert.equal((await call('pressure')).quarantineCount,1);
 await runtime.close();runtime=await launch();
 assert.deepEqual(await call('messages'),finalMessages);assert.deepEqual(await call('session'),session);
 const entries=await call('entries');assert.equal(new Set(entries.map(e=>e.seq)).size,entries.length);
 assert(entries.every((e,i)=>i===0||e.seq>entries[i-1].seq));
 await writeFile(join(directory,'evidence.json'),JSON.stringify({session,context:await call('context'),pressure:await call('pressure'),entries:entries.map(({seq,id,type})=>({seq,id,type})),messages:finalMessages},null,2));
 console.log('PASS: immutable large payloads, image accounting, range growth, resident fold, pinned instruction, quarantine, sequence order and process restart');
 console.log('artifacts',directory);
}finally{await runtime.close();}
